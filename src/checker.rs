    #[test]
    fn escape_free_locals_remain_partial_after_source_errors() {
        for (body, captures) in [
            ("missing; x", true),
            ("let nested = || { missing; x }; nested()", true),
            ("missing", false),
            ("let x = missing; x", false),
            ("Missing(field: x)", false), // the unknown struct's fields are unvisited
        ] {
            let source = format!("f(x: i32) -> void -> i32 {{ return (|| {{ {} }}) }}", body);
            let mut errors = vec![];
            let table = DeclTable::new(parse_program_str(&source, &mut errors));
            assert!(errors.is_empty());
            let declaration = &table.decls[0];
            let Decl::Func(function) = declaration else {
                panic!()
            };
            let mut checker = Checker::new();
            checker.check_decl(declaration, &table);
            assert!(checker
                .errors
                .iter()
                .any(|e| !e.message.contains("captured")));
            assert_eq!(
                checker
                    .errors
                    .iter()
                    .any(|e| e.message.contains("captured")),
                captures,
                "{}",
                source
            );
            let lambda = function
                .arena
                .exprs
                .iter()
                .rposition(|e| matches!(e, Expr::Lambda { .. }))
                .unwrap();
            let facts = CheckingBindings {
                arena: &function.arena,
                references: &checker.references,
                binders: &checker.binders,
                visited: &checker.visited,
            };
            let free = free_locals(&facts, lambda, []);
            assert!(!free.complete, "{}", source);
            assert_eq!(
                free.locals,
                if captures { vec![LocalId(0)] } else { vec![] }
            );
            assert_eq!(
                expr_capture_state(lambda, &facts, &HashMap::new()),
                if captures {
                    CaptureState::Capturing
                } else {
                    CaptureState::Unknown
                }
            );
        }
    }

    #[test]
    fn escape_diagnostics_preserve_editor_reference_and_type_trust() {
        let mut compiler = Compiler::new();
        compiler.quiet = true;
        assert!(compiler.parse("good() -> i32 { 42 } f(x: i32) -> void -> i32 { let failed = missing; return (|| { failed; x }) }", "partial-capture.lyte"));
        assert!(!compiler.analyze());
        assert!(compiler
            .last_type_errors
            .iter()
            .any(|e| e.message.contains("captured")));
        assert!(compiler.checked_program().is_none());
        let analysis = compiler.source_analysis().unwrap();
        let definition = analysis.declarations().named_ids(Name::str("f"))[0];
        let function = analysis.declarations().function(definition).unwrap();
        let body = analysis.body(definition).unwrap();
        for (id, expression) in function.arena.exprs.iter().enumerate() {
            if let Expr::Id(name) = expression {
                let facts = body.expression(id).unwrap();
                match name.as_str() {
                    "x" => {
                        assert!(matches!(facts.reference, Some(Reference::Local(_))));
                        assert_eq!(facts.ty, Some(mk_type(Type::Int32)));
                    }
                    "failed" => {
                        assert!(matches!(facts.reference, Some(Reference::Local(_))));
                        assert_eq!(facts.ty, None);
                    }
                    "missing" => {
                        assert_eq!(facts.reference, None);
                        assert_eq!(facts.ty, None);
                    }
                    _ => unreachable!(),
                }
            }
        }
        compiler.last_errors.clear();
        compiler.last_type_errors.clear();
        assert!(compiler.specialize().is_err());
        assert!(compiler.specialized_program().is_err());
    }

