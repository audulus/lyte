    #[test]
    fn escape_lambda_local_shadowing_does_not_capture_outer_binding() {
        for body in [
            "let x = 42; x",
            "var x = 42; x",
            "for x in 0 .. 2 { let use_x = x; }; 42",
            "let x = 42; let nested = || { x }; nested()",
        ] {
            let source = format!("f(x: i32) -> void -> i32 {{ return (|| {{ {} }}) }}", body);
            assert!(check(&source).is_empty(), "{}", source);
        }
        // The initializer still refers to the outer x before the new x is bound.
        let errors = check("f(x: i32) -> void -> i32 { return (|| { let x = x; x }) }");
        assert_eq!(errors.len(), 1, "{:?}", errors);
        assert!(errors[0].message.contains("captured"));
    }

