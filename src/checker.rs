#[derive(Clone, Copy, PartialEq, Eq)]
enum BindingKind {
    Parameter,
    LambdaParameter,
    Let,
    Var,
    For,
    SizeParameter,
}

/// One borrowed position across the recorded candidates. A reference in any
/// candidate requires assignability; slices and references both require no-alias.
struct BorrowedParameter {
    position: usize,
    reference: bool,
}

/// Type checking errors generated by
/// both the type checker and constraint
/// solver.
#[derive(Clone, Debug)]
pub struct TypeError {
    pub location: Loc,
    pub message: String,
}

/// Local variable declaration.
#[derive(Clone, Debug)]
struct Var {
    name: Name,
    ty: TypeID,
    mutable: bool,
    resolution: Reference,
}

/// Type-checks ASTs.
pub struct Checker {
    /// Overloads for arithmetic with built-in types.
    arith_overloads: Vec<TypeID>,

    /// Overloads for `%` with built-in types. Integers only: float modulo is
    /// provided by the `__mod` overloads in the stdlib, since no backend has a
    /// primitive float remainder instruction.
    mod_overloads: Vec<TypeID>,

    /// Overloads for casting.
    cast_overloads: Vec<TypeID>,

    /// Constraints on types.
    constraints: Vec<Constraint>,

    /// Current type variable instance.
    inst: Instance,

    /// Is an expression assignable?
    lvalue: Vec<bool>,

    /// Overloads for negation of built-in types.
    neg_overloads: Vec<TypeID>,

    /// Next anonymous type variable index.
    next_anon: usize,

    /// Overloads for relational operations with built-in types.
    rel_overloads: Vec<TypeID>,

    /// Expression types.
    pub types: Vec<TypeID>,

    /// Which expressions `check_expr` actually visited in the current function.
    /// Unvisited entries in `types` keep the fill value from `begin_body`,
    /// so post-check passes must skip them rather than trust their type.
    visited: Vec<bool>,

    /// Types established without solving: checked literals and reads of bindings
    /// with an explicit/fixed type. Never filled from a failed substitution.
    independent_types: Vec<Option<TypeID>>,

    /// Is an expression's value used, rather than discarded? See
    /// `mark_value_positions`.
    value_pos: Vec<bool>,

    /// Currently declared vars, as we're checking.
    vars: Vec<Var>,

    /// Accumulated type errors while checking.
    pub errors: Vec<TypeError>,

    /// Nesting depth of loops (>0 means we're inside a loop).
    loop_depth: usize,

    /// Return types of the enclosing functions and lambdas, innermost last.
    /// A `return` expression is constrained against the last entry.
    ret_types: Vec<TypeID>,

    // Construction state exists only while checking. A successful check freezes
    // it into canonical checked nodes; source syntax never owns solved meaning.
    references: Vec<Option<Reference>>,
    locals: Vec<Local>,
    local_kinds: Vec<BindingKind>,
    binders: Vec<Vec<LocalId>>,
    requirements: Vec<InterfaceRequirement>,
}

/// Returns true if the type is or contains a borrowed type (`[T]` or `&T`).
///
/// Borrowed types are only allowed as function parameters, not in struct fields or return types.
/// For function types, only the return type is checked (borrowed parameters are fine).
fn type_contains_bad_borrow(ty: TypeID) -> bool {
    match &*ty {
        Type::Slice(_) | Type::Reference(_) => true,
        Type::Array(elem, _) => type_contains_bad_borrow(*elem),
        Type::Tuple(types) => types.iter().any(|t| type_contains_bad_borrow(*t)),
        Type::Func(_, ret) => type_contains_bad_borrow(*ret),
        _ => false,
    }
}

fn bad_borrow_kind(ty: TypeID) -> &'static str {
    match &*ty {
        Type::Slice(_) => "slice",
        Type::Reference(_) => "reference",
        Type::Array(elem, _) => bad_borrow_kind(*elem),
        Type::Tuple(types) => types
            .iter()
            .find(|t| type_contains_bad_borrow(**t))
            .map(|t| bad_borrow_kind(*t))
            .unwrap_or("borrowed"),
        Type::Func(_, ret) => bad_borrow_kind(*ret),
        _ => "borrowed",
    }
}

/// Returns true if `ty` would be infinite in size due to a recursive struct definition.
///
/// `visiting` is the set of struct names currently on the DFS stack. Seed it with the
/// name of the struct being checked so that any path back to it is detected as a cycle.
fn type_is_recursive(ty: TypeID, decls: &DeclTable, visiting: &mut HashSet<Name>) -> bool {
    match &*ty {
        Type::Name(name, type_args) => {
            if visiting.contains(name) {
                return true;
            }
            // Only structs can contribute to infinite size; enums etc. are skipped.
            let struct_info: Option<(Vec<Name>, Vec<Field>)> =
                decls.find(*name).iter().find_map(|d| {
                    if let Decl::Struct(s) = d {
                        Some((s.typevars.clone(), s.fields.clone()))
                    } else {
                        None
                    }
                });
            if let Some((typevars, fields)) = struct_info {
                // Substitute generic parameters so we follow the concrete field types.
                let inst: Instance = typevars
                    .iter()
                    .zip(type_args.iter())
                    .map(|(tv, t)| (mk_type(Type::Var(*tv)), *t))
                    .collect();
                visiting.insert(*name);
                let recursive = fields
                    .iter()
                    .any(|f| type_is_recursive(f.ty.subst(&inst), decls, visiting));
                visiting.remove(name);
                recursive
            } else {
                false
            }
        }
        Type::Array(elem, _) | Type::Reference(elem) => type_is_recursive(*elem, decls, visiting),
        Type::Tuple(types) => types.iter().any(|t| type_is_recursive(*t, decls, visiting)),
        _ => false,
    }
}

impl Default for Checker {
    fn default() -> Self {
        Self::new()
    }
}

impl Checker {
    pub fn new() -> Self {
        let int8 = mk_type(Type::Int8);
        let int32: TypeID = mk_type(Type::Int32);
        let uint32: TypeID = mk_type(Type::UInt32);
        let types = [Type::Int32, Type::UInt32, Type::Float32, Type::Float64];
        let mut arith_overloads = vec![];
        let mut mod_overloads = vec![];
        let mut rel_overloads = vec![];
        let mut neg_overloads = vec![];
        let b = mk_type(Type::Bool);

        for ty in types {
            let is_int = matches!(ty, Type::Int32 | Type::UInt32);
            let t = mk_type(ty);
            let tt = tuple(vec![t, t]);
            arith_overloads.push(func(tt, t));
            if is_int {
                mod_overloads.push(func(tt, t));
            }
            rel_overloads.push(func(tt, b));
            neg_overloads.push(func(t, t));
        }

        // f32x4: arithmetic and negation, but not relational comparisons
        let f32x4 = mk_type(Type::Float32x4);
        let f32x4_pair = tuple(vec![f32x4, f32x4]);
        arith_overloads.push(func(f32x4_pair, f32x4));
        neg_overloads.push(func(f32x4, f32x4));

        let float32 = mk_type(Type::Float32);
        let float64 = mk_type(Type::Float64);
        let cast_overloads = vec![
            func(int8, int32),
            func(int32, int8),
            func(int32, uint32),
            func(uint32, int32),
            func(int32, float32),
            func(float32, int32),
            func(int32, float64),
            func(float64, int32),
            func(float32, float64),
            func(float64, float32),
        ];

        Self {
            types: vec![],
            visited: vec![],
            independent_types: vec![],
            value_pos: vec![],
            lvalue: vec![],
            inst: Instance::new(),
            next_anon: 0,
            vars: vec![],
            arith_overloads,
            mod_overloads,
            rel_overloads,
            neg_overloads,
            cast_overloads,
            constraints: vec![],
            errors: vec![],
            loop_depth: 0,
            ret_types: vec![],
            references: vec![],
            locals: vec![],
            local_kinds: vec![],
            binders: vec![],
            requirements: vec![],
        }
    }

    fn record_use(&mut self, expr: ExprID, resolution: Reference) {
        self.references[expr] = Some(resolution);
    }

    fn bind(
        &mut self,
        name: Name,
        ty: TypeID,
        mutable: bool,
        kind: BindingKind,
        binder: Option<ExprID>,
    ) {
        let id = LocalId(self.locals.len() as u32);
        self.locals.push(Local { name, ty, mutable });
        self.local_kinds.push(kind);
        if let Some(expr) = binder {
            self.binders[expr].push(id);
        }
        let resolution = if kind == BindingKind::SizeParameter {
            Reference::SizeParameter(id)
        } else {
            Reference::Local(id)
        };
        self.vars.push(Var {
            name,
            ty,
            mutable,
            resolution,
        });
    }

    fn eq(&mut self, lhs: TypeID, rhs: TypeID, loc: Loc, hint: &str) {
        let hint = if hint.is_empty() {
            None
        } else {
            Some(hint.to_string())
        };
        self.add_constraint(Constraint::Equal(lhs, rhs, loc, hint));
    }

    fn fresh(&mut self) -> TypeID {
        let t = mk_type(Type::Anon(self.next_anon));
        self.next_anon += 1;
        t
    }

    fn add_constraint(&mut self, c: Constraint) {
        // println!("adding constraint {:?}", &c);
        self.constraints.push(c);
    }

    fn check_int_literal_suffix(
        &mut self,
        id: ExprID,
        value: i64,
        suffix: IntLiteralSuffix,
        arena: &ExprArena,
        negative: bool,
    ) -> TypeID {
        let shown_value = if negative {
            format!("-{value}")
        } else {
            value.to_string()
        };

        match suffix {
            IntLiteralSuffix::I32 => {
                let max = if negative {
                    -(i32::MIN as i64)
                } else {
                    i32::MAX as i64
                };
                if value > max {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: format!("integer literal {shown_value} is out of range for i32"),
                    });
                }
                mk_type(Type::Int32)
            }
            IntLiteralSuffix::U32 => {
                if value > u32::MAX as i64 {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: format!("integer literal {value} is out of range for u32"),
                    });
                }
                mk_type(Type::UInt32)
            }
        }
    }

    fn check_unop(
        &mut self,
        id: ExprID,
        op: Unop,
        arg: ExprID,
        arena: &ExprArena,
        decls: &DeclTable,
    ) -> TypeID {
        match op {
            Unop::Neg => {
                // A leading `-` in literal position is considered by signed
                // suffix range checks, so `-2147483648i32` is valid even
                // though `2147483648i32` is not.
                if let Expr::Int(n, Some(suffix @ IntLiteralSuffix::I32)) = &arena[arg] {
                    let errors_before = self.errors.len();
                    let ty = self.check_int_literal_suffix(arg, *n, *suffix, arena, true);
                    self.visited[arg] = true;
                    if self.errors.len() == errors_before {
                        self.independent_types[arg] = Some(ty);
                    }
                    self.types[arg] = ty;
                    return ty;
                }

                let argt = self.check_expr(arg, arena, decls);
                let ft = self.fresh();
                let alts: Vec<_> = self
                    .neg_overloads
                    .iter()
                    .map(|t| Alt {
                        ty: *t,
                        interfaces: vec![],
                    })
                    .collect();

                self.add_constraint(Constraint::Or(ft, alts, arena.locs[id], None));

                let r = self.fresh();

                self.eq(
                    func(argt, r),
                    ft,
                    arena.locs[id],
                    "no match for unary negation",
                );

                r
            }
            Unop::Not => {
                let argt = self.check_expr(arg, arena, decls);
                self.eq(
                    argt,
                    mk_type(Type::Bool),
                    arena.locs[id],
                    &"logical negation requires a boolean",
                );

                mk_type(Type::Bool)
            }
        }
    }

    fn check_binop(
        &mut self,
        id: ExprID,
        op: Binop,
        lhs: ExprID,
        rhs: ExprID,
        arena: &ExprArena,
        decls: &DeclTable,
    ) -> TypeID {
        let at = self.check_expr(lhs, arena, decls);
        let bt = self.check_expr(rhs, arena, decls);

        if op.equality() {
            self.eq(at, bt, arena.locs[id], "equality requires matching types");

            mk_type(Type::Bool)
        } else if let Binop::Assign = op {
            // Lvalue check is deferred to check_lvalues() after type solving,
            // so that slice types are fully resolved.

            self.eq(at, bt, arena.locs[id], "assignment requires matching types");

            at
        } else if op.arithmetic() {
            let ft = self.fresh();

            let mut alts = vec![];

            let builtins = if op == Binop::Mod {
                &self.mod_overloads
            } else {
                &self.arith_overloads
            };

            for ty in builtins {
                alts.push(Alt {
                    ty: *ty,
                    interfaces: vec![],
                });
            }

            let overload_name = Name::new(op.overload_name().into());
            let candidates: Vec<_> = decls
                .named_ids(overload_name)
                .into_iter()
                .filter(|id| matches!(decls.definition(*id), Some(Decl::Func(_))))
                .collect();
            // Built-in arithmetic needs no named target. An empty optional
            // overload inventory is not an unresolved identifier reference.
            if !candidates.is_empty() {
                self.record_use(id, Reference::Functions(candidates));
            }
            for d in decls.find(overload_name) {
                if let Decl::Func(function) = d {
                    let Some(signature) = function.annotated_ty() else {
                        continue;
                    };
                    let dt = signature.fresh(&mut self.next_anon);
                    alts.push(Alt {
                        ty: dt,
                        interfaces: vec![],
                    });
                }
            }

            self.add_constraint(Constraint::Or(
                ft,
                alts,
                arena.locs[id],
                Some(format!("operator '{}'", format_binop(op))),
            ));

            let r = self.fresh();

            self.eq(
                func(tuple(vec![at, bt]), r),
                ft,
                arena.locs[id],
                "no match for arithmetic operator",
            );

            r
        } else if op.relational() {
            let ft = self.fresh();

            let mut alts = vec![];

            for ty in &self.rel_overloads {
                alts.push(Alt {
                    ty: *ty,
                    interfaces: vec![],
                });
            }

            self.add_constraint(Constraint::Or(
                ft,
                alts,
                arena.locs[id],
                Some(format!("comparison")),
            ));

            let b = mk_type(Type::Bool);

            self.eq(
                func(tuple(vec![at, bt]), b),
                ft,
                arena.locs[id],
                "no match for relational operator",
            );

            b
        } else {
            // And, Or — both operands should be bool, result is bool.
            let b = mk_type(Type::Bool);
            self.eq(
                at,
                b,
                arena.locs[id],
                "logical operator requires bool operands",
            );
            self.eq(
                bt,
                b,
                arena.locs[id],
                "logical operator requires bool operands",
            );
            b
        }
    }

    fn check_expr(&mut self, id: ExprID, arena: &ExprArena, decls: &DeclTable) -> TypeID {
        self.visited[id] = true;
        let errors_before = self.errors.len();
        let ty = match &arena[id] {
            Expr::True | Expr::False => mk_type(Type::Bool),
            Expr::Int(_, None) => {
                let ty = self.fresh();
                let alts = vec![
                    Alt {
                        ty: mk_type(Type::Int32),
                        interfaces: vec![],
                    },
                    // Alt {ty: mk_type(Type::UInt32), interfaces: vec![]},
                ];
                self.add_constraint(Constraint::Or(ty, alts, arena.locs[id], None));
                ty
            }
            Expr::Int(n, Some(suffix)) => {
                self.check_int_literal_suffix(id, *n, *suffix, arena, false)
            }
            Expr::Real(_, None) => mk_type(Type::Float32),
            Expr::Real(_, Some(FloatLiteralSuffix::F32)) => mk_type(Type::Float32),
            Expr::Real(_, Some(FloatLiteralSuffix::F64)) => mk_type(Type::Float64),
            Expr::Char(_) => mk_type(Type::Int8),
            Expr::String(s) => {
                let int8 = mk_type(Type::Int8);
                mk_type(Type::Array(
                    int8,
                    ArraySize::Known(s.bytes().len() as i32 + 1),
                ))
            }
            Expr::TypeApp(name, type_args) => {
                // Explicit type application: name⟨i32⟩.
                if let Some(Decl::Global { typevars, ty, .. }) = decls.find(*name).first() {
                    self.record_use(id, Reference::Global(decls.named_ids(*name)[0]));
                    self.lvalue[id] = true;
                    let mut inst = Instance::new();
                    for (tv, ta) in typevars.iter().zip(type_args.iter()) {
                        inst.insert(mk_type(Type::Var(*tv)), *ta);
                    }
                    ty.subst(&inst)
                } else {
                    // Function with explicit type args — collect all overloads
                    // whose typevar count matches, substitute the explicit type
                    // args, and let the solver pick the right arity.
                    let fn_decls = decls.find(*name);
                    let candidates = decls
                        .named_ids(*name)
                        .into_iter()
                        .filter(|id| {
                            matches!(decls.definition(*id), Some(Decl::Func(f))
                            if f.typevars.len() == type_args.len())
                        })
                        .collect();
                    self.record_use(id, Reference::Functions(candidates));
                    let mut alts: Vec<Alt> = Vec::new();
                    for d in fn_decls {
                        if let Decl::Func(fdecl) = d {
                            if let Some(signature) = fdecl
                                .annotated_ty()
                                .filter(|_| fdecl.typevars.len() == type_args.len())
                            {
                                let mut inst = Instance::new();
                                for (tv, ta) in fdecl.typevars.iter().zip(type_args.iter()) {
                                    inst.insert(mk_type(Type::Var(*tv)), *ta);
                                }
                                alts.push(Alt {
                                    ty: signature.subst(&inst),
                                    interfaces: vec![],
                                });
                            }
                        }
                    }
                    if alts.len() == 1 {
                        alts[0].ty
                    } else {
                        let t = self.fresh();
                        if !alts.is_empty() {
                            self.add_constraint(Constraint::Or(t, alts, arena.locs[id], None));
                        }
                        t
                    }
                }
            }
            Expr::Id(name) => {
                // Local variables will override all declarations.
                // Is this what we want?
                if let Some(v) = self.find(*name) {
                    self.record_use(id, v.resolution);
                    self.lvalue[id] = v.mutable;
                    v.ty
                } else if let Some(Decl::Global { typevars, ty, .. }) = decls.find(*name).first() {
                    self.record_use(id, Reference::Global(decls.named_ids(*name)[0]));
                    self.lvalue[id] = true;
                    if typevars.is_empty() {
                        *ty
                    } else {
                        // Generic global: freshen type variables so the solver
                        // can infer concrete types from usage context.
                        let mut inst = Instance::new();
                        for tv in typevars {
                            let fresh = self.fresh();
                            inst.insert(mk_type(Type::Var(*tv)), fresh);
                        }
                        ty.subst(&inst)
                    }
                } else {
                    let t = self.fresh();
                    let candidates = decls
                        .named_ids(*name)
                        .into_iter()
                        .filter(|id| {
                            matches!(
                                decls.definition(*id),
                                Some(Decl::Func(_) | Decl::Global { .. })
                            )
                        })
                        .collect();
                    self.record_use(id, Reference::Functions(candidates));
                    let alts: Vec<Alt> = decls
                        .alts(*name)
                        .iter()
                        .map(|alt| alt.fresh(&mut self.next_anon))
                        .collect();

                    if alts.is_empty() {
                        self.errors.push(TypeError {
                            location: arena.locs[id],
                            message: if decls
                                .find(*name)
                                .iter()
                                .any(|decl| matches!(decl, Decl::Func(_)))
                            {
                                format!("function '{}' has an incomplete parameter signature", name)
                            } else {
                                format!("undeclared identifier: {}", *name)
                            },
                        });
                    }

                    self.add_constraint(Constraint::Or(
                        t,
                        alts,
                        arena.locs[id],
                        Some(format!("'{}'", name)),
                    ));
                    t
                }
            }
            Expr::Unop(op, a) => self.check_unop(id, *op, *a, arena, decls),
            Expr::Binop(op, a, b) => self.check_binop(id, *op, *a, *b, arena, decls),
            Expr::AsTy(e, ty) => {
                let et = self.check_expr(*e, arena, decls);

                let ft = self.fresh();

                let mut alts = vec![];
                for ty in &self.cast_overloads {
                    alts.push(Alt {
                        ty: *ty,
                        interfaces: vec![],
                    });
                }

                self.add_constraint(Constraint::Or(ft, alts, arena.locs[id], None));

                self.eq(func(et, *ty), ft, arena.locs[id], "no match for cast");

                *ty
            }
            Expr::Call(f, args) => {
                let lhs = self.check_expr(*f, arena, decls);

                let ret = self.fresh();
                let v1 = self.fresh();
                self.eq(
                    self.types[*f],
                    func(v1, ret),
                    arena.locs[id],
                    "attempt to call a non-function",
                );

                let mut arg_types = vec![];
                for e in args {
                    self.check_expr(*e, arena, decls);
                    arg_types.push(self.types[*e]);
                }

                let ft = func(tuple(arg_types), ret);

                self.eq(
                    lhs,
                    ft,
                    arena.locs[id],
                    "argument types don't match function",
                );

                ret
            }
            Expr::Macro(name, args) => {
                let mut found = false;
                let mut macro_type = mk_type(Type::Void);

                // XXX: overloaded macros?
                for d in decls.find(*name) {
                    if let Decl::Macro(_) = d {
                        // Found our macro.
                        found = true;
                        macro_type = d.ty().fresh(&mut self.next_anon);
                    }
                }

                if !found {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: format!("unknown macro: {}", *name),
                    });
                }

                let mut arg_types = vec![];
                for e in args {
                    self.check_expr(*e, arena, decls);
                    arg_types.push(self.types[*e]);
                }

                let ret = self.fresh();
                let ft = func(tuple(arg_types), ret);

                self.eq(
                    macro_type,
                    ft,
                    arena.locs[id],
                    "arguments don't match macro definition",
                );

                ret
            }
            Expr::Field(lhs, name) => {
                let lhs_t = self.check_expr(*lhs, arena, decls);

                self.lvalue[id] = self.lvalue[*lhs];

                let t = self.fresh();

                self.constraints
                    .push(Constraint::Field(lhs_t, *name, t, arena.locs[id]));

                t
            }
            Expr::Enum(name) => {
                let t = self.fresh();
                let mut alts = vec![];

                // Find all the enum declarations with that name.
                decls.find_enum(*name, &mut |enum_name| {
                    let enum_ty = mk_type(Type::Name(enum_name, vec![]));
                    alts.push(Alt {
                        ty: enum_ty,
                        interfaces: vec![],
                    });
                });

                self.constraints.push(Constraint::Or(
                    t,
                    alts,
                    arena.locs[id],
                    Some(format!("enum case '.{}'", name)),
                ));

                t
            }
            Expr::Block(exprs) => {
                let n = self.vars.len();
                let mut t = mk_type(Type::Void);
                for e in exprs {
                    t = self.check_expr(*e, arena, decls);
                }
                while self.vars.len() > n {
                    self.vars.pop();
                }
                t
            }
            Expr::Var(name, init, ty) => {
                let ty = if let Some(ty) = ty { *ty } else { self.fresh() };

                if let Some(e) = init {
                    let init_ty = self.check_expr(*e, arena, decls);

                    self.eq(
                        ty,
                        init_ty,
                        arena.locs[id],
                        "variable initializer type must match",
                    );
                }

                self.bind(*name, ty, true, BindingKind::Var, Some(id));

                // A var declaration is a statement, not an expression: it does
                // not produce a value. Record the variable's type for the
                // backends (they read types[id] to size the slot), but report
                // the declaration itself as Void so an enclosing block or
                // if-else doesn't treat the declaration as its result. See
                // issue #22: codegen emits a placeholder i32 0 here, which used
                // to flow into a merge block typed from the declared type.
                self.types[id] = ty;
                return mk_type(Type::Void);
            }
            Expr::Let(name, init, ty) => {
                let ty = if let Some(ty) = ty { *ty } else { self.fresh() };

                let init_ty = self.check_expr(*init, arena, decls);

                self.eq(
                    ty,
                    init_ty,
                    arena.locs[id],
                    "variable initializer type must match",
                );

                self.bind(*name, ty, false, BindingKind::Let, Some(id));

                // A let declaration is a statement too — see the comment on
                // Expr::Var above.
                self.types[id] = ty;
                return mk_type(Type::Void);
            }
            Expr::Arena(block) => self.check_expr(*block, arena, decls),
            Expr::Return(expr) => {
                let ty = self.check_expr(*expr, arena, decls);

                // Constrain against the enclosing function's return type.
                // Without this, only a return in tail position is checked
                // (via the body's type), so an early return with the wrong
                // type reaches codegen and trips the backend's verifier.
                match self.ret_types.last() {
                    Some(&ret) => {
                        self.eq(
                            ty,
                            ret,
                            arena.locs[id],
                            "return type must match function return type",
                        );

                        // Take on the enclosing return type rather than the
                        // operand's, so a return in tail position doesn't
                        // report the same mismatch twice (once here, once
                        // from the body-level check below).
                        ret
                    }
                    None => ty,
                }
            }
            Expr::Assume(cond) => {
                self.check_expr(*cond, arena, decls);
                mk_type(Type::Void)
            }
            Expr::Break => {
                if self.loop_depth == 0 {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: "break outside of loop".to_string(),
                    });
                }
                mk_type(Type::Void)
            }
            Expr::Continue => {
                if self.loop_depth == 0 {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: "continue outside of loop".to_string(),
                    });
                }
                mk_type(Type::Void)
            }
            Expr::StructLit(struct_name, fields) => {
                // Look up the struct declaration.
                let d = decls.find(*struct_name);
                if let Some(Decl::Struct(st)) = d.first() {
                    // Create fresh type variables for generics.
                    let type_args: Vec<TypeID> = st.typevars.iter().map(|_| self.fresh()).collect();
                    let inst: crate::Instance = st
                        .typevars
                        .iter()
                        .map(|tv| mk_type(Type::Var(*tv)))
                        .zip(type_args.iter().copied())
                        .collect();

                    // Check each field.
                    for (fname, fval) in fields {
                        let val_ty = self.check_expr(*fval, arena, decls);
                        if let Some(field) = st.find_field(fname) {
                            let field_ty = field.ty.subst(&inst);
                            self.eq(
                                val_ty,
                                field_ty,
                                arena.locs[*fval],
                                &format!("struct field '{}' type mismatch", fname),
                            );
                        } else {
                            self.errors.push(TypeError {
                                location: arena.locs[*fval],
                                message: format!(
                                    "struct '{}' has no field '{}'",
                                    struct_name, fname
                                ),
                            });
                        }
                    }

                    // Check all fields are provided.
                    for field in &st.fields {
                        if !fields.iter().any(|(fname, _)| *fname == field.name) {
                            self.errors.push(TypeError {
                                location: arena.locs[id],
                                message: format!(
                                    "missing field '{}' in struct literal '{}'",
                                    field.name, struct_name
                                ),
                            });
                        }
                    }

                    mk_type(Type::Name(*struct_name, type_args))
                } else {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: format!("'{}' is not a struct", struct_name),
                    });
                    self.fresh()
                }
            }
            Expr::ArrayLiteral(exprs) => {
                if exprs.is_empty() {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: "empty array literals are not allowed".to_string(),
                    });
                }
                let t = self.fresh();
                for e in exprs {
                    let elem_t = self.check_expr(*e, arena, decls);
                    self.constraints
                        .push(Constraint::Equal(t, elem_t, arena.locs[*e], None));
                }
                mk_type(Type::Array(t, ArraySize::Known(exprs.len() as i32)))
            }
            Expr::ArrayIndex(array_expr, index_expr) => {
                let t = self.fresh();
                let array_t = self.check_expr(*array_expr, arena, decls);
                let idx_t = self.check_expr(*index_expr, arena, decls);

                // Preliminary lvalue: propagate from array expression.
                // The final check (including slice mutability) is done in
                // check_lvalues() after type solving.
                self.lvalue[id] = self.lvalue[*array_expr];

                // Probably should allow both signed and unsigned indexing?
                // self.eq(
                //     idx_t,
                //     mk_type(Type::Int32),
                //     arena.locs[*index_expr],
                //     "array index must be an i32",
                // );

                let alts: Vec<Alt> = vec![
                    Alt {
                        ty: mk_type(Type::Int32),
                        interfaces: vec![],
                    },
                    Alt {
                        ty: mk_type(Type::UInt32),
                        interfaces: vec![],
                    },
                ];

                self.add_constraint(Constraint::Or(
                    idx_t,
                    alts,
                    arena.locs[*index_expr],
                    Some("array index".into()),
                ));

                self.add_constraint(Constraint::ArrayOf(array_t, t, arena.locs[*array_expr]));
                t
            }
            Expr::Array(value, size) => {
                let value_t = self.check_expr(*value, arena, decls);
                let size_t = self.check_expr(*size, arena, decls);

                self.eq(
                    size_t,
                    mk_type(Type::Int32),
                    arena.locs[*size],
                    "array size must be an i32",
                );

                // Extract constant size when available (e.g. [0; 5]).
                let array_size = match &arena[*size] {
                    Expr::Int(n, _) => ArraySize::Known(*n as i32),
                    _ => ArraySize::Known(0),
                };

                mk_type(Type::Array(value_t, array_size))
            }
            Expr::While(cond, body) => {
                let cond_t = self.check_expr(*cond, arena, decls);
                self.eq(
                    cond_t,
                    mk_type(Type::Bool),
                    arena.locs[*cond],
                    "while loop control must be a bool",
                );
                self.loop_depth += 1;
                self.check_expr(*body, arena, decls);
                self.loop_depth -= 1;
                mk_type(Type::Void)
            }
            Expr::If(cond, then_expr, else_expr) => {
                let cond_t = self.check_expr(*cond, arena, decls);
                self.eq(
                    cond_t,
                    mk_type(Type::Bool),
                    arena.locs[*cond],
                    "if expression conditional must be a bool",
                );
                let then_t = self.check_expr(*then_expr, arena, decls);
                if let Some(else_expr) = else_expr {
                    let else_t = self.check_expr(*else_expr, arena, decls);
                    // When the if-else is used as a value, both branches must
                    // agree — it has a single type, and taking the then-branch's
                    // type without checking the else branch left the
                    // disagreement for codegen, which quietly substitutes a
                    // placeholder 0 (issue #22).
                    //
                    // In statement position the value is discarded, so branches
                    // are free to end in whatever their last statement happens
                    // to evaluate to (an assignment is an expression in lyte,
                    // so `if c { x = 1 } else { y = 2.0 }` is perfectly fine).
                    if self.value_pos[id] {
                        self.eq(
                            then_t,
                            else_t,
                            arena.locs[*else_expr],
                            "if-else branches must have the same type",
                        );
                    }
                    then_t
                } else {
                    mk_type(Type::Void)
                }
            }
            Expr::For {
                var,
                start,
                end,
                body,
            } => {
                let ty = mk_type(Type::Int32);
                let start_t = self.check_expr(*start, arena, decls);
                let end_t = self.check_expr(*end, arena, decls);
                self.eq(
                    start_t,
                    ty,
                    arena.locs[*start],
                    "start of for loop must be an integer",
                );
                self.eq(
                    end_t,
                    ty,
                    arena.locs[*start],
                    "end of for loop must be an integer",
                );

                self.bind(*var, ty, false, BindingKind::For, Some(id));

                self.loop_depth += 1;
                self.check_expr(*body, arena, decls);
                self.loop_depth -= 1;

                self.vars.pop();

                mk_type(Type::Void)
            }
            Expr::Tuple(exprs) => {
                let mut types = vec![];
                for e in exprs {
                    types.push(self.check_expr(*e, arena, decls));
                }
                mk_type(Type::Tuple(types))
            }
            Expr::Lambda { params, body } => {
                let n = self.vars.len();
                let mut param_types = vec![];
                for param in params {
                    let ty = param.ty.unwrap_or_else(|| self.fresh());
                    self.bind(
                        param.name,
                        ty,
                        false,
                        BindingKind::LambdaParameter,
                        Some(id),
                    );
                    param_types.push(ty);
                }

                // The lambda's return type isn't known up front, so bind a
                // fresh variable that both the body and any `return` inside
                // it unify with.
                let lambda_ret = self.fresh();
                self.ret_types.push(lambda_ret);
                let rt = self.check_expr(*body, arena, decls);
                self.ret_types.pop();
                self.eq(
                    rt,
                    lambda_ret,
                    arena.locs[*body],
                    "return type must match function return type",
                );

                while self.vars.len() > n {
                    self.vars.pop();
                }

                func(tuple(param_types), lambda_ret)
            }
            Expr::Error => self.fresh(),
        };
        if self.errors.len() == errors_before
            && (matches!(
                arena[id],
                Expr::True
                    | Expr::False
                    | Expr::Int(..)
                    | Expr::Real(..)
                    | Expr::Char(_)
                    | Expr::String(_)
            ) || matches!(
                (&arena[id], &self.references[id]),
                (
                    Expr::Id(_),
                    Some(Reference::Local(_) | Reference::SizeParameter(_))
                )
            ))
        {
            if ty != mk_type(Type::Void) {
                self.independent_types[id] = Some(ty);
            }
        }
        self.types[id] = ty;
        ty
    }

    fn find(&self, name: Name) -> Option<Var> {
        for v in self.vars.iter().rev() {
            if v.name == name {
                return Some(v.clone());
            }
        }
        None
    }

    /// Start an independent source body without manufacturing a function scope.
    fn begin_body(&mut self, arena: &ExprArena) {
        let n = arena.exprs.len();
        self.references = vec![None; n];
        self.locals.clear();
        self.local_kinds.clear();
        self.binders = vec![vec![]; n];
        self.requirements.clear();
        self.types = vec![mk_type(Type::Void); n];
        self.visited = vec![false; n];
        self.independent_types = vec![None; n];
        self.value_pos = vec![false; n];
        self.lvalue = vec![false; n];
        self.vars.clear();
        self.inst.clear();
        self.constraints.clear();
        self.ret_types.clear();
        self.loop_depth = 0;
    }

    fn check_expected_expr(
        &mut self,
        root: ExprID,
        arena: &ExprArena,
        decls: &DeclTable,
        expected: TypeID,
        message: &str,
    ) {
        let ty = self.check_expr(root, arena, decls);
        self.eq(ty, expected, arena.locs[root], message);
    }

    fn check_assumption(&mut self, arena: &ExprArena, cond: ExprID, decls: &DeclTable) {
        let errors_before = self.errors.len();
        self.begin_body(arena);
        mark_value_positions(cond, arena, true, &mut self.value_pos);
        // An assumption is a boolean-valued body. Preserve that expectation for
        // explicit returns in it as well, without constructing a function record.
        self.ret_types.push(mk_type(Type::Bool));
        self.check_expected_expr(
            cond,
            arena,
            decls,
            mk_type(Type::Bool),
            "assume condition must be a boolean expression",
        );
        self.ret_types.pop();
        self.solve_body(arena, decls, errors_before);
        let solved = self.solved_types();
        self.check_void_declarations(arena, &solved);
        if self.errors.len() == errors_before {
            self.check_unsolved_types(arena, &solved, false);
        }
    }

    fn check_fn_decl(&mut self, func_decl: &FuncDecl, decls: &DeclTable) {
        self.begin_body(&func_decl.arena);
        // `self.errors` accumulates across every decl in the table, so the
        // post-check passes below gate on errors from *this* function rather
        // than on the accumulator — otherwise one bad function silently
        // disables checking for every function after it.
        let errors_before = self.errors.len();

        // Disallow borrowed types in return position.
        if type_contains_bad_borrow(func_decl.ret) {
            self.errors.push(TypeError {
                location: func_decl.loc,
                message: format!(
                    "{} type {} is not allowed as a return type",
                    bad_borrow_kind(func_decl.ret),
                    func_decl.ret.pretty_print()
                ),
            });
        }

        if let Some(body) = func_decl.body {
            let body_used = func_decl.ret != mk_type(Type::Void);
            mark_value_positions(body, &func_decl.arena, body_used, &mut self.value_pos);
        }
        for &req in &func_decl.requires {
            mark_value_positions(req, &func_decl.arena, true, &mut self.value_pos);
        }

        for param in &func_decl.params {
            let ty = match param.ty {
                Some(ty) => ty,
                None => {
                    self.errors.push(TypeError {
                        location: func_decl.loc,
                        message: format!(
                            "parameter '{}' is missing a type annotation",
                            *param.name
                        ),
                    });
                    return;
                }
            };
            let (var_ty, mutable) = match &*ty {
                Type::Reference(inner) => (*inner, true),
                _ => (ty, false),
            };
            self.bind(param.name, var_ty, mutable, BindingKind::Parameter, None);
        }

        for (local, param) in self.locals.iter_mut().zip(&func_decl.params) {
            local.ty = param.ty.expect("checked parameter annotation");
        }

        // Size variables are available as i32 values in the body.
        for &sv in &func_decl.size_vars {
            self.bind(
                sv,
                mk_type(Type::Int32),
                false,
                BindingKind::SizeParameter,
                None,
            );
        }

        // Interface members retain their requirement and declaration IDs;
        // specialization selects only from these checked candidates.
        for (ordinal, constraint) in func_decl.constraints.iter().enumerate() {
            let requirement_id = RequirementId(ordinal as u32);
            let args = constraint
                .typevars
                .iter()
                .map(|name| typevar(name))
                .collect();
            if let Some(requirement) =
                decls.interface_requirement(requirement_id, constraint.interface_name, args)
            {
                for member in &requirement.members {
                    let function = decls
                        .function(member.definition)
                        .expect("checked interface member");
                    self.vars.push(Var {
                        name: function.name,
                        ty: member.signature,
                        mutable: false,
                        resolution: Reference::InterfaceMember {
                            requirement: requirement_id,
                            member: member.definition,
                        },
                    });
                }
                self.requirements.push(requirement);
            } else {
                self.errors.push(TypeError {
                    location: func_decl.loc,
                    message: format!("unknown interface: {}", constraint.interface_name),
                });
            }
        }

        // Type-check require clauses: each must have type bool.
        for &req in &func_decl.requires {
            self.check_expected_expr(
                req,
                &func_decl.arena,
                decls,
                mk_type(Type::Bool),
                "require clause must be a boolean expression",
            );
        }

        // Prototypes still own checked parameters and preconditions.
        if let Some(body) = func_decl.body {
            self.ret_types.push(func_decl.ret);
            let ty = self.check_expr(body, &func_decl.arena, decls);
            self.ret_types.pop();

            if func_decl.ret != mk_type(Type::Void) {
                self.eq(
                    ty,
                    func_decl.ret,
                    func_decl.arena.locs[body],
                    "return type must match function return type",
                );
            }
        }
        self.solve_body(&func_decl.arena, decls, errors_before);
    }

    fn solve_body(&mut self, arena: &ExprArena, decls: &DeclTable, errors_before: usize) {
        self.vars.clear();

        if self.errors.len() == errors_before {
            solve_constraints(
                &mut self.constraints,
                &mut self.inst,
                decls,
                &mut self.errors,
            );
        }

        // Check lvalue validity now that types are solved.
        if self.errors.len() == errors_before {
            self.check_lvalues(arena, decls);
        }

        // Check that no two borrowed parameters alias (Fortran-style no-alias rule).
        if self.errors.len() == errors_before {
            self.check_slice_aliasing(arena, decls);
        }
    }

    /// Check that all assignments have valid lvalue targets, using solved types
    /// to determine slice mutability.
    fn check_lvalues(&mut self, arena: &ExprArena, decls: &DeclTable) {
        for id in 0..arena.exprs.len() {
            if let Expr::Binop(Binop::Assign, lhs, _) = &arena[id] {
                if !self.is_lvalue(*lhs, arena) {
                    self.errors.push(TypeError {
                        location: arena.locs[id],
                        message: "left-hand side of assignment isn't assignable".to_string(),
                    });
                }
            }

            if let Expr::Call(f, args) = &arena[id] {
                for parameter in self.borrowed_parameters(*f, arena, decls) {
                    if !parameter.reference {
                        continue;
                    }
                    let pos = parameter.position;
                    if pos < args.len() && !self.is_lvalue(args[pos], arena) {
                        self.errors.push(TypeError {
                            location: arena.locs[args[pos]],
                            message: "reference argument must be assignable".to_string(),
                        });
                    }
                }
            }
        }
    }

    /// Classify borrowing once for both post-solve consumers. Recorded overloads
    /// (including explicit TypeApp candidates) retain the conservative union;
    /// local and other function-valued callees use their solved signature.
    fn borrowed_parameters(
        &self,
        callee: ExprID,
        arena: &ExprArena,
        decls: &DeclTable,
    ) -> Vec<BorrowedParameter> {
        let mut borrowed: Vec<BorrowedParameter> = Vec::new();
        let mut add = |position, ty: TypeID| {
            if matches!(*ty, Type::Slice(_) | Type::Reference(_)) {
                let reference = matches!(*ty, Type::Reference(_));
                if let Some(parameter) = borrowed.iter_mut().find(|p| p.position == position) {
                    parameter.reference |= reference;
                } else {
                    borrowed.push(BorrowedParameter {
                        position,
                        reference,
                    });
                }
            }
        };
        let mut found_function = false;
        if let Some(Reference::Functions(candidates)) = &self.references[callee] {
            for &candidate in candidates {
                if let Some(function) = decls.function(candidate) {
                    found_function = true;
                    let explicit: Instance = match &arena[callee] {
                        Expr::TypeApp(_, args) => function
                            .typevars
                            .iter()
                            .zip(args)
                            .map(|(&var, &ty)| (mk_type(Type::Var(var)), ty))
                            .collect(),
                        _ => Instance::new(),
                    };
                    for (position, parameter) in function.params.iter().enumerate() {
                        if let Some(ty) = parameter.ty {
                            add(position, ty.subst(&explicit));
                        }
                    }
                }
            }
        }
        // A recorded set can contain only function-valued globals. Without an
        // actual function declaration, borrowing comes from the solved signature.
        if !found_function {
            if let Type::Func(from, _) = &*self.types[callee].subst(&self.inst) {
                if let Type::Tuple(params) = &**from {
                    for (position, &ty) in params.iter().enumerate() {
                        add(position, ty);
                    }
                }
            }
        }
        borrowed
    }

    /// Enforce the no-alias rule: two borrowed parameters in the same call must not
    /// refer to the same underlying memory. Since Lyte has no sub-slicing, two
    /// arguments alias iff they are the same variable (or same field path).
    ///
    /// This enables Fortran-style `restrict` semantics: the compiler (and LLVM
    /// backend) can assume slice parameters never overlap, enabling load hoisting,
    /// store reordering, and vectorization.
    fn check_slice_aliasing(&mut self, arena: &ExprArena, decls: &DeclTable) {
        for id in 0..arena.exprs.len() {
            let Expr::Call(f, args) = &arena[id] else {
                continue;
            };

            let borrowed = self.borrowed_parameters(*f, arena, decls);
            if borrowed.len() < 2 {
                continue;
            }

            // Collect base paths for arguments at borrowed positions.
            let mut borrow_args: Vec<Vec<Name>> = Vec::new();
            for parameter in &borrowed {
                let pos = parameter.position;
                if pos < args.len() {
                    if let Some(path) = expr_base_path(args[pos], arena) {
                        borrow_args.push(path);
                    }
                }
            }

            // Check all pairs for aliasing.
            for i in 0..borrow_args.len() {
                for j in (i + 1)..borrow_args.len() {
                    if borrow_args[i] == borrow_args[j] {
                        let name = borrow_args[i]
                            .iter()
                            .map(|n| n.as_str())
                            .collect::<Vec<_>>()
                            .join(".");
                        self.errors.push(TypeError {
                            location: arena.locs[id],
                            message: if borrowed.iter().all(|p| !p.reference) {
                                format!(
                                    "cannot pass '{}' to multiple slice parameters \
                                     (slices must not alias)",
                                    name
                                )
                            } else {
                                format!(
                                    "cannot pass '{}' to multiple borrowed parameters \
                                     (borrowed arguments must not alias)",
                                    name
                                )
                            },
                        });
                    }
                }
            }
        }
    }

    /// Determine if an expression is an lvalue, using solved types.
    fn is_lvalue(&self, id: ExprID, arena: &ExprArena) -> bool {
        match &arena[id] {
            Expr::Id(_) | Expr::TypeApp(_, _) => self.lvalue[id],
            Expr::Field(lhs, _) => self.is_lvalue(*lhs, arena),
            Expr::ArrayIndex(array_expr, _) => {
                // Slice indexing is always an lvalue (slices are mutable references).
                let solved_ty = self.types[*array_expr].subst(&self.inst);
                if matches!(*solved_ty, Type::Slice(_)) {
                    return true;
                }
                // Array indexing is an lvalue only if the array itself is.
                self.is_lvalue(*array_expr, arena)
            }
            _ => false,
        }
    }

    fn check_struct_decl(&mut self, st: &StructDecl, decls: &DeclTable) {
        let mut names = HashSet::new();

        for field in &st.fields {
            if names.contains(&field.name) {
                self.errors.push(TypeError {
                    location: field.loc,
                    message: format!("repeated field: {}", &field.name),
                })
            } else {
                names.insert(field.name);
            }

            field.ty.typevars(&mut |name| {
                if !st.typevars.iter().any(|n| *n == name) {
                    self.errors.push(TypeError {
                        location: field.loc,
                        message: format!("unknown type variable: {}", name),
                    })
                }
            })
        }

        // Disallow slice types in struct fields.
        for field in &st.fields {
            if type_contains_bad_borrow(field.ty) {
                self.errors.push(TypeError {
                    location: field.loc,
                    message: format!(
                        "{} type {} is not allowed in struct fields (use a sized array instead)",
                        bad_borrow_kind(field.ty),
                        field.ty.pretty_print()
                    ),
                })
            }
        }

        // Disallow recursive struct definitions (they would be unbounded in size).
        let mut visiting = HashSet::new();
        visiting.insert(st.name);
        for field in &st.fields {
            if type_is_recursive(field.ty, decls, &mut visiting) {
                self.errors.push(TypeError {
                    location: field.loc,
                    message: format!("struct '{}' is recursive", st.name),
                });
                break;
            }
        }
    }

    fn check_interface(&mut self, _name: Name, funcs: &[FuncDecl]) {
        for func in funcs {
            if func.body.is_some() {
                self.errors.push(TypeError {
                    location: func.loc,
                    message: format!("interface function can't have body: {}", func.name),
                })
            }
        }
    }

    fn _check_decl(&mut self, decl: &Decl, decls: &DeclTable) {
        match decl {
            Decl::Func(func_decl) => self.check_fn_decl(func_decl, decls),
            Decl::Macro(func_decl) => self.check_fn_decl(func_decl, decls),
            Decl::Assume { arena, cond } => self.check_assumption(arena, *cond, decls),
            Decl::Interface(Interface { name, funcs, .. }) => self.check_interface(*name, funcs),
            Decl::Struct(struct_decl) => self.check_struct_decl(struct_decl, decls),
            _ => (),
        }
    }

    pub fn check(&mut self, decls: &DeclTable) {
        for decl in &decls.decls {
            self.check_decl(decl, decls);
        }
    }

    pub fn check_decl(&mut self, decl: &Decl, decls: &DeclTable) {
        let errors_before = self.errors.len();
        self._check_decl(decl, decls);
        if let Decl::Func(fd) | Decl::Macro(fd) = decl {
            if let Some(body) = fd.body {
                let facts = CheckingBindings {
                    arena: &fd.arena,
                    references: &self.references,
                    binders: &self.binders,
                    visited: &self.visited,
                };
                escape_walk(body, &facts, &mut HashMap::new(), &mut self.errors);
            }
            // Both post-solve passes read the same substituted types, so
            // compute them once.
            let solved_types = self.solved_types();
            self.check_void_declarations(&fd.arena, &solved_types);
            if self.errors.len() == errors_before {
                self.check_unsolved_types(&fd.arena, &solved_types, !fd.typevars.is_empty());
            }
        }
    }

    /// Reject variables declared with type void.
    ///
    /// Void isn't a value type in lyte — there's nothing to store and nothing
    /// you can later do with the binding — so a void-typed declaration is
    /// always a mistake. Reporting it here points at the declaration rather
    /// than at whatever first tried to use the variable.
    ///
    /// Skips expressions `check_expr` never visited: those keep the Void fill
    /// value from `check_fn_decl` and would otherwise look like void
    /// declarations. That guard is what lets this run regardless of earlier
    /// errors — gating on `self.errors`, which accumulates across decls, meant
    /// one error in the first function disabled the check for every later one.
    ///
    /// A function that reported its own error still won't produce this
    /// diagnostic, since `check_fn_decl` skips constraint solving there and
    /// the declaration's type is left an unsolved type variable.
    fn check_void_declarations(&mut self, arena: &ExprArena, solved_types: &[TypeID]) {
        for (i, expr) in arena.exprs.iter().enumerate() {
            let name = match expr {
                Expr::Let(name, _, _) | Expr::Var(name, _, _) => name,
                _ => continue,
            };
            if !self.visited.get(i).copied().unwrap_or(false) {
                continue;
            }
            if i < solved_types.len() && matches!(&*solved_types[i], Type::Void) {
                self.errors.push(TypeError {
                    location: arena.locs[i],
                    message: format!("variable '{}' cannot have type void", name),
                });
            }
        }
    }

    /// Detect unsolved type variables in non-generic functions.
    /// The caller skips this when the function itself reported an error:
    /// unsolved vars are usually a symptom of an earlier type error, and a
    /// function whose constraints never got solved has nothing but unsolved
    /// vars.
    fn check_unsolved_types(
        &mut self,
        arena: &ExprArena,
        solved_types: &[TypeID],
        is_generic: bool,
    ) {
        for (i, solved) in solved_types.iter().enumerate() {
            // For generic functions, Type::Var is expected (they have named
            // type parameters). Only flag anonymous type variables (Anon),
            // which indicate the solver couldn't resolve an inference.
            let has_problem = if is_generic {
                solved.contains_anon()
            } else {
                solved.contains_var()
            };
            if has_problem {
                if i < arena.locs.len() {
                    self.errors.push(TypeError {
                        location: arena.locs[i],
                        message: format!(
                            "could not fully infer type (resolved to {})",
                            solved.pretty_print()
                        ),
                    });
                    break;
                }
            }
        }
    }

    /// Retain a bounded view of this check, without constructing checked syntax
    /// for erroneous expressions. A concrete substitution left by failed solving
    /// is not evidence: only a successful body may publish inferred types.
    pub(crate) fn body_analysis(
        &self,
        source: &FuncDecl,
        analysis: &SourceAnalysis,
    ) -> BodyAnalysis {
        let source_trusted = analysis.source_is_trusted(source);
        let solved = self.solved_types();
        let complete = source_trusted
            && self.errors.is_empty()
            && self
                .references
                .iter()
                .flatten()
                .all(|r| analysis.reference_is_trusted(r))
            && self
                .types
                .iter()
                .chain(&solved)
                .all(|ty| analysis.type_is_valid(*ty, source));
        let available =
            |ty: TypeID| (source_trusted && analysis.type_is_available(ty, source)).then_some(ty);
        let mut locals: Vec<_> = self
            .locals
            .iter()
            .map(|local| AnalyzedLocal {
                name: local.name,
                ty: available(if complete {
                    local.ty.subst(&self.inst)
                } else {
                    local.ty
                })
                .filter(|ty| *ty != mk_type(Type::Void)),
                loc: source.loc,
            })
            .collect();
        for (expr, binders) in self.binders.iter().enumerate() {
            for binder in binders {
                locals[binder.index()].loc = source.arena.locs[expr];
            }
        }
        let expressions = source
            .arena
            .exprs
            .iter()
            .enumerate()
            .map(|(id, expr)| {
                if !self.visited[id] {
                    return ExpressionFacts::default();
                }
                let reference = self.references[id]
                    .clone()
                    .filter(|reference| match reference {
                        Reference::Functions(candidates) => !candidates.is_empty(),
                        Reference::Local(local) | Reference::SizeParameter(local) => {
                            !locals[local.index()].name.is_empty()
                        }
                        _ => true,
                    });
                let ty = if complete {
                    available(if matches!(expr, Expr::Let(..) | Expr::Var(..)) {
                        mk_type(Type::Void)
                    } else {
                        solved[id]
                    })
                } else {
                    self.independent_types[id].and_then(available)
                };
                ExpressionFacts {
                    ty,
                    reference,
                    binding: if matches!(expr, Expr::Let(..) | Expr::Var(..) | Expr::For { .. }) {
                        self.binders[id].first().copied()
                    } else {
                        None
                    },
                }
            })
            .collect();
        BodyAnalysis {
            expressions,
            locals,
            requirements: self
                .requirements
                .iter()
                .map(|req| (req.id, req.interface))
                .collect(),
        }
    }

    /// Freeze a successfully checked source body. Expression references and
    /// solved types become one node; declaration types belong to local records.
    pub(crate) fn checked_body(&self, source: &ExprArena) -> CheckedBody {
        assert!(
            self.errors.is_empty(),
            "cannot publish an invalid checked body"
        );
        let locals: Vec<Local> = self
            .locals
            .iter()
            .cloned()
            .map(|mut local| {
                local.ty = local.ty.subst(&self.inst);
                local
            })
            .collect();
        let solved = self.solved_types();
        let mut nodes = Vec::with_capacity(source.exprs.len());
        for (id, expression) in source.exprs.iter().enumerate() {
            let resolution = || self.references[id].clone().expect("checked reference");
            let binder = || *self.binders[id].first().expect("checked binder");
            let kind = match expression {
                Expr::Id(_) => CheckedExpr::Id(resolution()),
                Expr::TypeApp(_, args) => CheckedExpr::TypeApp(
                    resolution(),
                    args.iter().map(|t| t.subst(&self.inst)).collect(),
                ),
                Expr::Let(_, init, _) => CheckedExpr::Let(binder(), *init, None),
                Expr::Var(_, init, _) => CheckedExpr::Var(binder(), *init, None),
                Expr::For {
                    start, end, body, ..
                } => CheckedExpr::For {
                    var: binder(),
                    start: *start,
                    end: *end,
                    body: *body,
                },
                Expr::Lambda { body, .. } => CheckedExpr::Lambda {
                    params: self.binders[id]
                        .iter()
                        .map(|&local| CheckedParam { local })
                        .collect(),
                    body: *body,
                },
                Expr::Int(v, s) => CheckedExpr::Int(*v, *s),
                Expr::Real(v, s) => CheckedExpr::Real(v.clone(), *s),
                Expr::Call(f, a) => CheckedExpr::Call(*f, a.clone()),
                Expr::Binop(op, a, b) => CheckedExpr::Binop(*op, *a, *b),
                Expr::Unop(op, a) => CheckedExpr::Unop(*op, *a),
                Expr::String(v) => CheckedExpr::String(v.clone()),
                Expr::Char(v) => CheckedExpr::Char(*v),
                Expr::Field(a, n) => CheckedExpr::Field(*a, *n),
                Expr::Array(a, b) => CheckedExpr::Array(*a, *b),
                Expr::ArrayLiteral(a) => CheckedExpr::ArrayLiteral(a.clone()),
                Expr::ArrayIndex(a, b) => CheckedExpr::ArrayIndex(*a, *b),
                Expr::True => CheckedExpr::True,
                Expr::False => CheckedExpr::False,
                Expr::AsTy(a, t) => CheckedExpr::AsTy(*a, t.subst(&self.inst)),
                Expr::If(a, b, c) => CheckedExpr::If(*a, *b, *c),
                Expr::While(a, b) => CheckedExpr::While(*a, *b),
                Expr::Block(v) => CheckedExpr::Block(v.clone()),
                Expr::Return(a) => CheckedExpr::Return(*a),
                Expr::Break => CheckedExpr::Break,
                Expr::Continue => CheckedExpr::Continue,
                Expr::Enum(n) => CheckedExpr::Enum(*n),
                Expr::Tuple(v) => CheckedExpr::Tuple(v.clone()),
                Expr::StructLit(n, v) => CheckedExpr::StructLit(*n, v.clone()),
                Expr::Arena(a) => CheckedExpr::Arena(*a),
                Expr::Assume(a) => CheckedExpr::Assume(*a),
                Expr::Macro(..) | Expr::Error => {
                    panic!("unexpanded or invalid source in checked body")
                }
            };
            let ty = if matches!(expression, Expr::Let(..) | Expr::Var(..)) {
                mk_type(Type::Void)
            } else {
                solved[id]
            };
            nodes.push(CheckedNode {
                kind,
                ty,
                loc: source.locs[id],
            });
        }
        // Operator overloading is lowered while publishing checked meaning,
        // rather than rewriting source syntax after its types have been solved.
        for id in 0..nodes.len() {
            if let CheckedExpr::Binop(op, lhs, rhs) = nodes[id].kind.clone() {
                if op.arithmetic()
                    && (matches!(*nodes[lhs].ty, Type::Name(_, _))
                        || (op == Binop::Mod
                            && matches!(*nodes[lhs].ty, Type::Float32 | Type::Float64)))
                {
                    let Some(reference) = self.references[id].clone() else {
                        continue;
                    };
                    let callee = nodes.len();
                    nodes.push(CheckedNode {
                        kind: CheckedExpr::Id(reference),
                        ty: func(tuple(vec![nodes[lhs].ty, nodes[rhs].ty]), nodes[id].ty),
                        loc: nodes[id].loc,
                    });
                    nodes[id].kind = CheckedExpr::Call(callee, vec![lhs, rhs]);
                }
            }
        }
        CheckedBody::from_parts(nodes, locals, self.requirements.clone())
    }

    /// Publish function metadata only at the function boundary.
    pub fn checked_function(&self, source: &FuncDecl) -> CheckedFunction {
        let arena = self.checked_body(&source.arena);
        let params = self
            .local_kinds
            .iter()
            .enumerate()
            .filter_map(|(i, kind)| {
                (*kind == BindingKind::Parameter).then(|| CheckedParam {
                    local: LocalId(i as u32),
                })
            })
            .collect();
        CheckedFunction {
            name: source.name,
            typevars: source.typevars.clone(),
            size_vars: source
                .size_vars
                .iter()
                .copied()
                .zip(
                    self.local_kinds
                        .iter()
                        .enumerate()
                        .filter_map(|(index, kind)| {
                            (*kind == BindingKind::SizeParameter).then_some(LocalId(index as u32))
                        }),
                )
                .map(|(symbol, local)| crate::checked::SizeParameter { symbol, local })
                .collect(),
            params,
            body: source.body,
            ret: source.ret.subst(&self.inst),
            requires: source.requires.clone(),
            loc: source.loc,
            arena,
            closure_vars: vec![],
            is_extern: source.is_extern,
        }
    }

    /// Returns types we've solved for.
    pub fn solved_types(&self) -> Vec<TypeID> {
        self.types.iter().map(|t| t.subst(&self.inst)).collect()
    }

    pub fn print_errors(&self) {
        for err in &self.errors {
            print_error_with_context(err.location, &err.message);
        }
    }
}

/// Mark which expressions have their value used, as opposed to discarded.
///
/// Lyte blocks evaluate to their last expression, and an assignment is an
/// expression, so plenty of statements produce values nobody looks at. The
/// distinction matters for if-else: when the value is used both branches have
/// to produce the same type, and when it's discarded they don't have to
/// produce anything at all.
///
/// A value is discarded in a non-final element of a block and in a loop body.
/// Everywhere else the parent uses it, and a block's or branch's last
/// expression inherits the position of the construct it belongs to.
fn mark_value_positions(id: ExprID, arena: &ExprArena, used: bool, value_pos: &mut [bool]) {
    value_pos[id] = used;
    match &arena[id] {
        Expr::Block(exprs) => {
            for (i, e) in exprs.iter().enumerate() {
                let is_last = i + 1 == exprs.len();
                mark_value_positions(*e, arena, used && is_last, value_pos);
            }
        }
        Expr::If(cond, then_expr, else_expr) => {
            mark_value_positions(*cond, arena, true, value_pos);
            mark_value_positions(*then_expr, arena, used, value_pos);
            if let Some(else_expr) = else_expr {
                mark_value_positions(*else_expr, arena, used, value_pos);
            }
        }
        Expr::While(cond, body) => {
            mark_value_positions(*cond, arena, true, value_pos);
            mark_value_positions(*body, arena, false, value_pos);
        }
        Expr::For {
            start, end, body, ..
        } => {
            mark_value_positions(*start, arena, true, value_pos);
            mark_value_positions(*end, arena, true, value_pos);
            mark_value_positions(*body, arena, false, value_pos);
        }
        Expr::Arena(inner) => mark_value_positions(*inner, arena, used, value_pos),
        other => {
            for child in other.subexprs() {
                mark_value_positions(child, arena, true, value_pos);
            }
        }
    }
}

/// Extract the "base path" of an expression — the chain of identifiers and field
/// names that uniquely identifies the storage location. Returns None for complex
/// expressions (calls, indexing, literals) where aliasing can't be determined
/// syntactically.
///
/// Examples:
///   `x`       → Some(["x"])
///   `s.arr`   → Some(["s", "arr"])
///   `f(x)`    → None
///   `a[i]`    → None
fn expr_base_path(id: ExprID, arena: &ExprArena) -> Option<Vec<Name>> {
    match &arena[id] {
        Expr::Id(name) => Some(vec![*name]),
        Expr::Field(base, field) => {
            let mut path = expr_base_path(*base, arena)?;
            path.push(*field);
            Some(path)
        }
        _ => None,
    }
}

/// Binding-only view of this check. It deliberately has no solved types and
/// remains usable when source errors prevent checked-program publication.
struct CheckingBindings<'a> {
    arena: &'a ExprArena,
    references: &'a [Option<Reference>],
    binders: &'a [Vec<LocalId>],
    visited: &'a [bool],
}

impl BindingFacts for CheckingBindings<'_> {
    fn binding_node(&self, id: ExprID) -> BindingNode {
        let mut node = BindingNode {
            children: self.arena[id].subexprs(),
            used: None,
            declared: self.binders[id].clone(),
            complete: self.visited[id],
        };
        match &self.arena[id] {
            Expr::Id(_) | Expr::TypeApp(_, _) => match &self.references[id] {
                Some(Reference::Local(local)) => node.used = Some(*local),
                None => node.complete = false,
                Some(Reference::Functions(candidates)) if candidates.is_empty() => {
                    node.complete = false;
                }
                _ => {}
            },
            Expr::Error | Expr::Macro(..) => node.complete = false,
            _ => {}
        }
        node
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum CaptureState {
    Noncapturing,
    Unknown,
    Capturing,
}

impl CaptureState {
    fn union(self, other: Self) -> Self {
        match (self, other) {
            (Self::Capturing, _) | (_, Self::Capturing) => Self::Capturing,
            (Self::Unknown, _) | (_, Self::Unknown) => Self::Unknown,
            _ => Self::Noncapturing,
        }
    }
}

/// Preserve the existing escape traversal and conservative call-result taint.
/// Binding IDs remove scope reconstruction: taint for a departed scope cannot
/// affect a sibling binding. Implicit returns, assignment propagation and returns
/// inside lambda bodies remain outside this analysis.
fn escape_walk(
    expr: ExprID,
    facts: &CheckingBindings<'_>,
    tainted: &mut HashMap<LocalId, CaptureState>,
    errors: &mut Vec<TypeError>,
) {
    match &facts.arena[expr] {
        Expr::Return(value) => {
            escape_walk(*value, facts, tainted, errors);
            if expr_capture_state(*value, facts, tainted) == CaptureState::Capturing {
                errors.push(TypeError {
                    location: facts.arena.locs[*value],
                    message: "closure with captured variables cannot be returned \
                              (captured addresses would dangle after the frame exits)"
                        .to_string(),
                });
            }
        }
        Expr::Lambda { .. } => {}
        Expr::Let(_, init, _) | Expr::Var(_, Some(init), _) => {
            escape_walk(*init, facts, tainted, errors);
            let state = expr_capture_state(*init, facts, tainted);
            if let Some(&local) = facts.binders[expr].first() {
                tainted.insert(local, state);
            }
        }
        expression => {
            for child in expression.subexprs() {
                escape_walk(child, facts, tainted, errors);
            }
        }
    }
}

/// Unknown facts cannot prove noncapture or create an escape error. A resolved
/// free-local use is sufficient to diagnose capture even with other facts missing.
fn expr_capture_state(
    expr: ExprID,
    facts: &CheckingBindings<'_>,
    tainted: &HashMap<LocalId, CaptureState>,
) -> CaptureState {
    match &facts.arena[expr] {
        Expr::Lambda { .. } => {
            let free = free_locals(facts, expr, []);
            if !free.locals.is_empty() {
                CaptureState::Capturing
            } else if free.complete {
                CaptureState::Noncapturing
            } else {
                CaptureState::Unknown
            }
        }
        Expr::Id(_) => {
            let node = facts.binding_node(expr);
            if let Some(local) = node.used {
                tainted
                    .get(&local)
                    .copied()
                    .unwrap_or(CaptureState::Noncapturing)
            } else if node.complete {
                CaptureState::Noncapturing
            } else {
                CaptureState::Unknown
            }
        }
        Expr::Error => CaptureState::Unknown,
        Expr::Block(exprs) => exprs.last().map_or(CaptureState::Noncapturing, |e| {
            expr_capture_state(*e, facts, tainted)
        }),
        Expr::If(_, then, else_) => expr_capture_state(*then, facts, tainted).union(
            else_.map_or(CaptureState::Noncapturing, |e| {
                expr_capture_state(e, facts, tainted)
            }),
        ),
        // Calls conservatively carry capture from either callee or arguments,
        // including laundering patterns such as `return identity(capturing)`.
        Expr::Call(callee, args) => args
            .iter()
            .fold(expr_capture_state(*callee, facts, tainted), |state, arg| {
                state.union(expr_capture_state(*arg, facts, tainted))
            }),
        _ => CaptureState::Noncapturing,
    }
}

