    #[test]
    fn borrowed_explicit_type_applications_keep_the_recorded_candidate_union() {
        for callee in ["call", "call⟨i32⟩"] {
            let errors = check(&format!(
                "call<T>(a: T) {{}} call<T>(a: &T, flag: bool) {{}} main {{ {}(1) }}",
                callee
            ));
            assert_eq!(errors.len(), 1, "{:?}", errors);
            assert!(errors[0]
                .message
                .contains("reference argument must be assignable"));

            let errors = check(&format!(
                "call<T>(a: &T, b: T) {{}} call<T>(a: T, b: &T, flag: bool) {{}} main {{ var x = 1; {}(x, x) }}", callee
            ));
            assert_eq!(errors.len(), 1, "{:?}", errors);
            assert!(errors[0].message.contains("multiple borrowed parameters"));
        }
        // Explicit application recorded only the one-type-argument overload.
        assert!(check("call<T>(a: T) {} call<T, U>(a: &T) {} main { call⟨i32⟩(1) }").is_empty());
        // Explicit type arguments can themselves introduce a borrowed type.
        let errors = check("call<T>(a: T) {} main { call⟨&i32⟩(1) }");
        assert_eq!(errors.len(), 1, "{:?}", errors);
        assert!(errors[0]
            .message
            .contains("reference argument must be assignable"));
        let errors = check("call<T>(a: T, b: T) {} main { var x = 1; call⟨&i32⟩(x, x) }");
        assert_eq!(errors.len(), 1, "{:?}", errors);
        assert!(errors[0].message.contains("multiple borrowed parameters"));
    }

